# main/assistants/router.py
"""
Ресепшен Нейро-команды.
Слой 1 — правила (бесплатно и мгновенно).
Слой 2 — Qwen-роутер для сообщений, которые правила не распознали.
Возвращает код интента; специалиста выбирает оркестратор.
"""

import re

from main.llm_utils import call_llm, INJECTION_GUARD, user_block

# ---------------------------------------------------------------------------
# Категории интентов — единый словарь для всего бота
# ---------------------------------------------------------------------------
WORD = 'word'              # разбор конкретного слова
THEORY = 'theory'          # термин/правило: «что такое метонимия»
ESSAY = 'essay'            # сочинение (задание 27)
STATS = 'stats'            # свой прогресс и статистика
EGE = 'ege'                # процедура экзамена
MARKETING = 'marketing'    # тарифы/цены/оплата/пробный
SUPPORT = 'support'        # техническая проблема
MOTIVATION = 'motivation'  # усталость, тревога, нужна поддержка
PLATFORM = 'platform'      # что умеет платформа, как начать, кто ты
CLARIFY = 'clarify'        # не распознали

# ---------------------------------------------------------------------------
# Словари-триггеры (порядок проверок важен — см. classify)
# ---------------------------------------------------------------------------

_SUPPORT = ('не работает', 'не заходит', 'не могу войти', 'не открывается',
            'не входит', 'пароль', 'ошибка', 'сбой', 'глюк', 'завис',
            'не приходит', 'оплатил', 'оплатила', 'списал', 'не засчитал',
            'пропал доступ', 'не вижу')

_ESSAY = ('сочинен', 'задание 27', 'задания 27', 'задач 27')

_STATS = ('статистик', 'мой прогресс', 'мои ошибк', 'мои результат',
          'слаб', 'сколько я решил', 'сколько решил')

_MOTIVATION = ('устал', 'устала', 'боюсь', 'страшно', 'пережива', 'лень',
               'не могу больше', 'хочу бросить', 'ничего не получается',
               'стресс', 'волнуюсь', 'паник', 'выгорел', 'опускаются руки')

_WORD_TRIGGERS = ('как пишется', 'как правильно писать', 'почему',
                  'правописание', 'написание', 'часть речи', 'какая часть речи',
                  'разбор слова', 'проверочное слово')

_THEORY_TRIGGERS = ('что такое', 'что это такое', 'объясни', 'расскажи про',
                    'расскажи о', 'чем отличается', 'чем различаются',
                    'в чем разница', 'правило', 'определение', 'когда ставится',
                    'когда пишется', 'в каких случаях', 'как отличить')

# Подсказки терминов из задания 26 и частых тем — чтобы теория не падала в ЕГЭ
_TERM_HINTS = ('метоним', 'эпитет', 'метафор', 'литот', 'гипербол', 'сравнен',
               'фразеолог', 'парцелляц', 'инверс', 'анафор', 'эпифор',
               'оксюморон', 'риторич', 'ряд однородных', 'выразительн',
               'причастн', 'деепричастн', 'ударени', 'пароним')

_EGE = ('егэ', 'огэ', 'экзамен', 'апелляц', 'критери', 'сколько времени',
        'сколько длится', 'первичн', 'вторичн', 'бланк', 'пробник')

_MARKETING = ('тариф', 'цена', 'стоим', 'оплат', 'купить', 'пробн', 'подписк',
              'рассроч', 'вычет', 'скидк', 'сколько стоит')

_PLATFORM = ('кто ты', 'что ты умеешь', 'что умеешь', 'как ты работаешь',
             'как начать', 'с чего начать', 'нейростат', 'платформ',
             'планинг', 'слово дня', 'квиз', 'диагностик', 'помощь',
             'привет', 'здравствуй', 'добрый')


# «Сам справлюсь / хватит ли бесплатного» — это продажный вопрос, а не процедура ЕГЭ
def is_self_prep(message: str) -> bool:
    m = (message or '').lower()
    self_keys = ('самостоятельн', 'самому', 'сам подготов', 'подготовиться сам',
                 'без репетитора', 'без преподавател', 'тариф 0', 'тарифом 0',
                 'на тарифе 0', 'с тарифом 0', 'на бесплатном', 'бесплатно',
                 'с бесплатным', 'на бесплатн')
    goal_keys = ('подготов', 'хватит', 'справлюсь', 'сдам', 'реально',
                 'нормально', 'получится', 'смогу')
    return any(k in m for k in self_keys) and any(k in m for k in goal_keys)


def _is_single_word(message: str) -> bool:
    """Сообщение состоит из одного слова (например, просто «вода»)."""
    tokens = re.findall(r'[а-яёa-z-]{2,}', message.lower())
    return len(tokens) == 1


def classify(message: str) -> str:
    """Слой 1: правила. Порядок проверок = приоритет."""
    m = (message or '').lower().strip()

    # 1. Техпроблема — раньше всех: это точка оттока
    if any(k in m for k in _SUPPORT):
        return SUPPORT

    # 2. Сочинение — раньше теории и маркетинга
    if any(k in m for k in _ESSAY):
        return ESSAY

    # 3. Своя статистика
    if any(k in m for k in _STATS):
        return STATS

    # 4. Эмоции и поддержка
    if any(k in m for k in _MOTIVATION):
        return MOTIVATION

    # 5. Одиночное слово без вопроса → разбор слова,
    #    кроме слов-пунктов меню («привет», «тарифы», «апелляция»…)
    if _is_single_word(m):
        override = {
            'привет': PLATFORM, 'здравствуй': PLATFORM, 'помощь': PLATFORM,
            'тариф': MARKETING, 'тарифы': MARKETING, 'цена': MARKETING,
            'цены': MARKETING, 'оплата': MARKETING,
            'статистика': STATS, 'прогресс': STATS,
            'апелляция': EGE, 'егэ': EGE, 'огэ': EGE,
        }.get(m.strip())
        if override:
            return override
        return WORD

    # 6. Явные триггеры разбора слова
    if any(k in m for k in _WORD_TRIGGERS):
        return WORD

    # 7. Теория — раньше процедуры ЕГЭ и маркетинга
    if any(k in m for k in _THEORY_TRIGGERS) or any(k in m for k in _TERM_HINTS):
        return THEORY

    # 7.5 «Справлюсь ли сам / с бесплатным тарифом» — в продажи, а не в процедуру
    if is_self_prep(m):
        return MARKETING

    # 8. Процедура экзамена
    if any(k in m for k in _EGE):
        return EGE

    # 9. Тарифы и оплата
    if any(k in m for k in _MARKETING):
        return MARKETING

    # 10. Платформа и ориентация
    if any(k in m for k in _PLATFORM):
        return PLATFORM

    return CLARIFY


_ROUTES = (WORD, THEORY, ESSAY, STATS, EGE, MARKETING, SUPPORT,
           MOTIVATION, PLATFORM)


def classify_with_llm(message: str) -> str:
    """Слой 2: Qwen-роутер (дешёвый вызов ~10 токенов)."""
    system = (
        "Ты — ресепшен образовательной платформы Нейростат. "
        "Отнеси сообщение ученика ровно к одной категории и верни ТОЛЬКО её код.\n"
        "word — спрашивает про написание или часть речи конкретного слова\n"
        "theory — просит объяснить правило, термин или понятие русского языка\n"
        "essay — про сочинение\n"
        "stats — про свой прогресс, статистику, ошибки\n"
        "ege — про экзамен и подготовку к нему: время, баллы, критерии, апелляция, "
        "бланки, как готовиться, как распределить время, реально ли за полгода\n"
        "marketing — тарифы, цены, оплата, пробный период, скидки\n"
        "support — техническая проблема с сайтом или ботом\n"
        "motivation — усталость, тревога, потеря мотивации, нужна поддержка\n"
        "platform — спрашивает, что умеет платформа, как начать, кто ассистент\n"
        "other — не подходит ни к одной\n"
        + INJECTION_GUARD
    )
    try:
        raw = call_llm(
            [{"role": "system", "content": system},
             {"role": "user", "content": user_block(message, 300)}],
            max_tokens=10, timeout=10
        )
        raw = (raw or '').strip().lower()
        for code in _ROUTES:
            if code in raw:
                return code
    except Exception as e:
        print(f"⚠️ LLM-роутер недоступен: {e}")
    return CLARIFY


def route(message: str) -> str:
    """Единая точка маршрутизации: правила → LLM."""
    intent = classify(message)
    if intent == CLARIFY:
        intent = classify_with_llm(message)
    return intent
