# main/assistants/marketing.py
"""
Нейро-маркетолог
Отвечает на вопросы о тарифах, возможностях платформы, помогает с выбором
"""

from main.llm_utils import call_deepseek, get_fallback_response


class Marketing:
    def handle(self, user, message, context, history=None):
        """Обрабатывает запрос к маркетологу"""
        
        # Пробуем LLM
        try:
            prompt = self._build_marketing_prompt(message, user.username, user.email or '')
            reply = call_deepseek(prompt)
            return reply
        except Exception as e:
            print(f"Marketing LLM error: {e}")
            # Fallback без LLM
            return self._get_fallback_response(message)
    
    def _build_marketing_prompt(self, message, username, user_email):
        """Формирует промпт для DeepSeek"""
        
        system_prompt = """Ты — Нейро-маркетолог образовательной платформы "Нейростат".

Твоя задача:
1. Презентовать возможности платформы понятно и убедительно
2. Помогать с выбором тарифа под потребности ученика
3. Отвечать на вопросы об оплате, пробном периоде, возвратах
4. Быть дружелюбным, но не навязчивым
5. При необходимости — направлять на страницу оплаты

ВАЖНО:
- Не обещай того, чего нет в тарифах
- Если не знаешь ответа — предложи связаться с администратором
- Используй эмодзи умеренно (🎯 ✅ 💡)"""

        # Контекст о пользователе (для персонализации)
        user_context = f"""
        Пользователь: {username}
        Email: {user_email if user_email else 'не указан'}
        """

        # База знаний о тарифах (можно вынести в JSON/БД)
        tariffs_info = """
        ТАРИФЫ ПЛАТФОРМЫ:
        
        🆓 Базовый (бесплатно):
        • Квизы по орфографии и ударениям
        • Личный кабинет и статистика
        • До 10 слов в планинге
        
        ⭐ Стандарт (299₽/мес):
        • Всё из Базового
        • Безлимитный планинг
        • Персональные рекомендации
        • Недельные отчёты
        
        🏆 Премиум (599₽/мес):
        • Всё из Стандарта
        • Приоритетная поддержка
        • Доступ к закрытым материалам
        • Индивидуальный план обучения
        """

        user_prompt = f"""
        {user_context}
        
        {tariffs_info}
        
        ВОПРОС ПОЛЬЗОВАТЕЛЯ: {message}
        
        ОТВЕТ (кратко, по делу, 2-4 предложения):"""

        return [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_prompt}
        ]
    
    def _get_fallback_response(self, message):
        """Ответ без LLM (если API недоступно)"""
        
        message_lower = message.lower()
        
        if 'тариф' in message_lower or 'цена' in message_lower or 'стоим' in message_lower:
            return """💡 У нас 3 тарифа:

🆓 Базовый — бесплатно (квизы, до 10 слов в планинге)
⭐ Стандарт — 299₽/мес (безлимитный планинг, рекомендации)
🏆 Премиум — 599₽/мес (всё + приоритетная поддержка)

Подробности: /profile/"""
        
        if 'оплат' in message_lower or 'купить' in message_lower:
            return """💳 Перейти к оплате можно в Личном кабинете: /profile/

Принимаем карты РФ, СБП. Есть пробный период 7 дней!"""
        
        if 'пробн' in message_lower or 'тест' in message_lower:
            return """✅ Да, у нас есть пробный период 7 дней для тарифа Стандарт!

Активируется автоматически при первом переходе на тариф."""
        
        if 'привет' in message_lower:
            return f"""Привет! 👋 Я Нейро-маркетолог платформы "Нейростат".

Могу рассказать:
• О тарифах и возможностях
• Как начать обучение
• Об оплате и пробном периоде

Спроси меня о чём угодно!"""
        
        if 'помощ' in message_lower:
            return """💡 Я помогу:

• Выбрать тариф под твои задачи
• Рассказать о возможностях платформы
• Подсказать, как начать обучение

Что тебя интересует?"""
        
        return """🤔 Не совсем понял вопрос.

Могу рассказать:
• О тарифах (напиши "тарифы")
• Об оплате (напиши "оплата")
• О пробном периоде (напиши "пробный")

Или спроси про обучение — я переключу на Нейро-преподавателя!"""